  function lookup(code, text) {
    var dict = DICT[code];
    if (dict && Object.prototype.hasOwnProperty.call(dict, text)) return dict[text];
    var extra = EXTRA[code];
    if (extra && Object.prototype.hasOwnProperty.call(extra, text)) return extra[text];
    return null;
  }

  function pick(list, n) {
    if (typeof list === 'string') return list.replace(/\{n\}/g, n);
    if (list.length > 2) {
      var n10 = n % 10;
      var n100 = n % 100;
      var index = (n10 === 1 && n100 !== 11) ? 0
        : (n10 >= 2 && n10 <= 4 && (n100 < 12 || n100 > 14)) ? 1
          : 2;
      return list[index].replace(/\{n\}/g, n);
    }
    return (n === 1 ? list[0] : list[1]).replace(/\{n\}/g, n);
  }

  function count(code, kind, n) {
    var table = COUNTS[code];
    if (!table || !table[kind]) return n + ' ' + kind + (n === 1 ? '' : 's');
    return pick(table[kind], n);
  }

  function translate(code, value) {
    if (code === 'en' || !DICT[code]) return value;
    var text = String(value == null ? '' : value);
    var m = text.match(/^(\s*)([\s\S]*?)(\s*)$/);
    if (!m) return value;
    var lead = m[1], core = m[2], tail = m[3];
    if (!core) return value;

    var exact = lookup(code, core);
    if (exact !== null) return lead + exact + tail;

    var hit;
    if ((hit = core.match(/^(\d+)\s+notes?$/))) return lead + count(code, 'note', +hit[1]) + tail;
    if ((hit = core.match(/^(\d+)\s+matches?$/))) return lead + count(code, 'match', +hit[1]) + tail;
    if ((hit = core.match(/^(\d+)\s+characters?$/))) return lead + count(code, 'char', +hit[1]) + tail;
    if ((hit = core.match(/^(\d+)\s+words?$/))) return lead + count(code, 'word', +hit[1]) + tail;
    if ((hit = core.match(/^(\d+)\s+min read$/))) return lead + count(code, 'read', +hit[1]) + tail;
    if ((hit = core.match(/^(\d+)\s+notes? ready$/))) return lead + count(code, 'ready', +hit[1]) + tail;
    if ((hit = core.match(/^(\d+)\s+models?\. Choose one above\.$/))) return lead + count(code, 'model', +hit[1]) + '. ' + (lookup(code, 'Choose one above') || 'Choose one above.') + tail;
    if ((hit = core.match(/^(\d+)\s+spelling errors?\s*📝$/))) return lead + count(code, 'error', +hit[1]) + ' 📝' + tail;
    if ((hit = core.match(/^Edited\s+(.+)$/))) return lead + (lookup(code, 'Edited') || 'Edited') + ' ' + hit[1] + tail;
    if ((hit = core.match(/^Saved\s+(.+)$/))) return lead + (lookup(code, 'Saved') || 'Saved') + ' ' + hit[1] + tail;
    if ((hit = core.match(/^Last edited\s+(.+)$/))) return lead + (lookup(code, 'Last edited') || 'Last edited') + ' ' + hit[1] + tail;
    if ((hit = core.match(/^Updated\s+(.+)$/))) return lead + (lookup(code, 'Updated') || 'Updated') + ' ' + hit[1] + tail;
    if ((hit = core.match(/^Moved to\s+(.+)$/))) return lead + (lookup(code, 'Moved to') || 'Moved to') + ' ' + hit[1] + tail;
    if ((hit = core.match(/^Added\s+(.+)$/))) return lead + (lookup(code, 'Added') || 'Added') + ' ' + hit[1] + tail;
    if ((hit = core.match(/^No notes with\s+#(.+)$/))) return lead + (lookup(code, 'No notes with') || 'No notes with') + ' #' + hit[1] + tail;
    if ((hit = core.match(/^No notes contain\s+“(.+)”\.$/))) return lead + (lookup(code, 'No notes contain') || 'No notes contain') + ' “' + hit[1] + '”.' + tail;
    if ((hit = core.match(/^Share\s+“(.+)”$/))) return lead + (lookup(code, 'Share') || 'Share') + ' “' + hit[1] + '”' + tail;
    if ((hit = core.match(/^Translate\s+·\s+(.+)$/))) return lead + (lookup(code, 'Translate') || 'Translate') + ' · ' + hit[1] + tail;
    if ((hit = core.match(/^No commands or notes match\s+“(.+)”\.$/))) return lead + (lookup(code, 'No commands or notes match') || 'No commands or notes match') + ' “' + hit[1] + '”.' + tail;

    return value;
  }

